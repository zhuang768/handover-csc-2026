export type ExtraKey = keyof typeof extraEn;
export function translate(language: Language, key: TextKey | ExtraKey): string {
  if (key in extraEn)
    return language === "zh"
      ? extraZh[key as ExtraKey]
      : extraEn[key as ExtraKey];
  return language === "zh" ? zh[key as TextKey] : en[key as TextKey];
}
